-- NutriTrack — Temporary Password Migration
-- File   : temp_password_migration.sql
-- Purpose: Adds is_temp_password column to health_workers table
--          to track whether the account is still using the
--          system-generated temporary password.
-- Run    : Once on your database (safe to re-run — uses IF NOT EXISTS)
-- ============================================================

-- Step 1: Add is_temp_password column to health_workers table
-- 0 = normal password (set by the user)
-- 1 = temporary password (auto-generated by system on account creation)

ALTER TABLE health_workers
    ADD COLUMN IF NOT EXISTS is_temp_password TINYINT(1) NOT NULL DEFAULT 0
    COMMENT '1 = account is using system-generated temp password, 0 = user has their own password';

